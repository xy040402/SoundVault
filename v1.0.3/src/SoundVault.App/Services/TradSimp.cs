    private static readonly Dictionary<char, char> Map = Build();

    public static string ToSimp(string s)
    {
        if (string.IsNullOrEmpty(s)) return s;

        bool any = false;
        foreach (var ch in s) if (Map.ContainsKey(ch)) { any = true; break; }
        if (!any) return s;

        var sb = new StringBuilder(s.Length);
        foreach (var ch in s) sb.Append(Map.TryGetValue(ch, out var v) ? v : ch);
        return sb.ToString();
    }

    /// <summary>反查表：简体 → 繁体（给界面繁体化用）。</summary>
    public static IEnumerable<KeyValuePair<char, char>> ReversePairs()
    {
        foreach (var kv in Map) yield return new KeyValuePair<char, char>(kv.Value, kv.Key);
    }

    public static bool HasTrad(string s)
    {
        foreach (var ch in s) if (Map.ContainsKey(ch)) return true;
        return false;
    }

